    // ============================================================
    // ระบบ Dialogue Tree
    // ============================================================
    public DialogueNode getDialogueTree(int level) {
        return switch (level) {
            case 1 -> buildLevel1Tree();
            case 2 -> buildLevel2Tree();
            case 3 -> buildLevel3Tree();
            case 4 -> buildLevel4Tree();
            case 5 -> buildLevel5Tree();
            default -> buildLevel1Tree();
        };
    }

